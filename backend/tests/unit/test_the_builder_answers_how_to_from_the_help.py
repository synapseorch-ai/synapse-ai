"""How-to answers come from the product's own help; what it cannot do is said, with what it can (BWA1, D274).

BWA1's Nova Pro baseline answered "How do I connect Slack?" with a screen that does not exist and promised an
iPhone app, a phone call and a guaranteed Google ranking. These pin:

- `native_builder/help_topics.json` is the "?" panel's help (`frontend/src/lib/help.ts`), regenerated by
  `frontend/scripts/help-topics.mjs`: this fails when help.ts changes and the JSON does not;
- `search_help` finds the screen a how-to question is about, with the screen's path, and says when nothing does;
- `product_capabilities` says what the product does not do and the nearest thing that does; a host replaces it;
- the builder's answering agent, operator and analyst hold both.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from core import builder_help
from core.builder_tools import execute_builder_tool_with_events

HELP_TS = Path(__file__).resolve().parents[3] / "frontend" / "src" / "lib" / "help.ts"


async def _call(tool: str, **args) -> dict:
    raw, _ = await execute_builder_tool_with_events(tool, args, server_module=None)
    return json.loads(raw)


@pytest.mark.skipif(not HELP_TS.exists(), reason="the frontend is not beside this backend")
def test_the_json_is_the_help_panels_words():
    ts = HELP_TS.read_text()
    body = ts[ts.index("HELP_TOPICS"):]
    keys = set(re.findall(r"^    '?([a-z_.]+)'?: \{\s*$", body, re.M))
    titles = set(re.findall(r"^        title: '([^']+)'", body, re.M)) | set(
        re.findall(r'^        title: "([^"]+)"', body, re.M))
    data = json.loads((Path(builder_help.__file__).parent / "native_builder" / "help_topics.json").read_text())
    assert set(data) == keys, "help.ts changed: run `node --experimental-strip-types frontend/scripts/help-topics.mjs`"
    assert {t["title"] for t in data.values()} == titles, "help.ts changed: regenerate help_topics.json"


@pytest.mark.parametrize("question,title", [
    ("How do I connect Slack?", "Channels"),
    ("How do I put an agent on my website?", "Widgets"),
    ("how do i make a workflow run every weekday at 9?", "Schedules"),
    ("I have an OpenAPI spec for our booking system. How do I turn it into tools?", "Tools"),
])
async def test_a_how_to_question_finds_its_screen_first(question, title):
    found = (await _call("search_help", question=question))["topics"]
    assert found[0]["title"] == title, [t["title"] for t in found]
    assert found[0]["steps"] and found[0]["where"]


async def test_the_key_question_finds_the_models_screen():
    found = (await _call("search_help", question="Where do I put my own OpenAI key?"))["topics"]
    assert "Models" in [t["title"] for t in found]


async def test_nothing_found_is_said_not_invented():
    got = await _call("search_help", question="zzqx flurble")
    assert got["topics"] == [] and "do not invent a screen" in got["note"]


async def test_what_it_cannot_do_is_said_with_the_nearest_thing():
    text = (await _call("product_capabilities"))["capabilities"]
    assert "does not build native mobile or desktop apps" in text and "Nearest:" in text
    assert "never takes card numbers or passwords" in text


async def test_a_host_says_its_own():
    builder_help.set_capabilities("Cloud: what it does.")
    try:
        assert (await _call("product_capabilities"))["capabilities"] == "Cloud: what it does."
    finally:
        builder_help.set_capabilities(None)
    builder_help.set_help_index({"x": {"title": "Only topic", "summary": "Connect a thing", "steps": ["a"]}})
    try:
        assert [t["title"] for t in (await _call("search_help", question="connect"))["topics"]] == ["Only topic"]
    finally:
        builder_help.set_help_index(None)


def test_the_answering_agent_holds_both_and_the_planner_is_handed_the_capabilities():
    """The reporter reads both; since SAI2-P3 the planner's pack carries the capabilities, read by code, so its
    `cannot` names the nearest thing that works (the operator and the analyst are gone)."""
    import inspect

    from core.native_builder import build_plan, bundled_definitions
    roles = {a["system_role"]: a for a in bundled_definitions()["agents"]}
    assert {"search_help", "product_capabilities"} <= set(roles["reporter"]["tools"])
    assert "product_capabilities" in inspect.getsource(build_plan.read_plan_context)
